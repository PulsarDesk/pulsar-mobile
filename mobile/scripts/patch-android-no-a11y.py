#!/usr/bin/env python3
# Strip the control AccessibilityService from the app manifest, for the DEFAULT
# release APK.
#
# Google Play Protect refuses to install an app downloaded through a browser (or a
# messenger / file manager) when its manifest declares an accessibility service —
# "this app can access sensitive information" — with no override offered. So the APK
# people download from the release page must not declare one, and the phone-as-host
# remote-touch feature (PulsarA11yService, declared by the tauri-plugin-pulsar-video
# manifest) is shipped separately as the "host-control" APK, installed over adb.
#
# The plugin's manifest is merged into the app's; a `tools:node="remove"` entry with the
# same android:name in the APP manifest drops the service from the merged result. The
# class still compiles into the APK — only the manifest entry is gone — and the plugin's
# `a11yAvailable` command reports that, so the host screen knows to offer screen sharing
# only. Idempotent; run AFTER `tauri android init` (gen/ is regenerated by it).
import sys

p = sys.argv[1]
s = open(p, encoding="utf-8").read()

SERVICE = "dev.pulsar.video.PulsarA11yService"
TOOLS_NS = 'xmlns:tools="http://schemas.android.com/tools"'
REMOVE = f'''        <!-- Default APK: no accessibility service (see scripts/patch-android-no-a11y.py). -->
        <service android:name="{SERVICE}" tools:node="remove" />
'''

if TOOLS_NS not in s:
    s = s.replace(
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android"',
        f'<manifest xmlns:android="http://schemas.android.com/apk/res/android"\n    {TOOLS_NS}',
        1,
    )
    assert TOOLS_NS in s, "manifest root element not found"

if f'android:name="{SERVICE}" tools:node="remove"' not in s:
    marker = "    </application>"
    assert marker in s, "</application> not found"
    s = s.replace(marker, REMOVE + marker, 1)

open(p, "w", encoding="utf-8").write(s)
print("patched", p, "- accessibility service removed from the merged manifest")

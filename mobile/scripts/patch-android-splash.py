#!/usr/bin/env python3
# Patch the tauri-generated android project with the branded splash screen:
#   - res/values{,-night}/pulsar_splash_colors.xml: the connect screen's colours (page
#     background, its soft brand/cyan glows) and the brand mark colour, light + dark
#   - res/values-v31 + values-night-v31/themes.xml: system splash (API 31+) in those colours
#   - res/drawable/splash_icon.xml: the Pulsar mark in the brand colour, animated like the
#     desktop launch splash, sized for the splash icon's central safe zone (the
#     full-bleed launcher icon looked oversized/cropped as a splash)
#   - MainActivity.onCreate: a native splash overlay — the connect screen's gradient (the
#     system splash only takes a flat colour) + the same animated mark, held
#     SPLASH_HOLD_MS (700 in production) and faded out; it also hides the still-empty
#     first webview frames + enableEdgeToEdge (an edit that previously lived only in an
#     uncommitted gen/ file, so CI builds lacked it).
#
# gen/android is regenerated by `tauri android init` (CI does this every release
# build), so these changes cannot be committed there — run this script after any
# init, like patch-android-signing.py. Idempotent.
import os, sys

GEN = sys.argv[1] if len(sys.argv) > 1 else "gen/android"
APP = os.path.join(GEN, "app/src/main")
# How long the MainActivity splash overlay stays up before it fades out.
SPLASH_HOLD_MS = 700

# sRGB of the mobile UI tokens (ui/css/tokens.css) the connect screen paints with:
# --bg, --brand-soft, --cyan-soft, and the mark colour (light: --accent; dark: the
# desktop's dark-theme --mark oklch(0.74 0.15 272)).
COLORS = {
    "values": {"bg": "#FBFDFE", "glow": "#E8EFFF", "glow2": "#D7F7FF", "mark": "#4E60E8"},
    "values-night": {"bg": "#0D0F15", "glow": "#232B4C", "glow2": "#05343D", "mark": "#8AA3FF"},
}
for qual, c in COLORS.items():
    d = os.path.join(APP, "res", qual)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "pulsar_splash_colors.xml"), "w") as f:
        f.write("<resources>\n" + "".join(
            f'    <color name="pulsar_splash_{k}">{v}</color>\n' for k, v in c.items()) + "</resources>\n")
    print(f"  + res/{qual}/pulsar_splash_colors.xml")

# ── 1) drawable/splash_icon.xml — animated pulse rings, inset to the icon safe zone ──
drawable_dir = os.path.join(APP, "res/drawable")
os.makedirs(drawable_dir, exist_ok=True)
splash_icon = """<?xml version="1.0" encoding="utf-8"?>
<!-- Pulsar mark for the Android 12+ splash, ANIMATED exactly like the desktop launch
     splash (pulsar-desktop src/app.css `splash-pulse`): the whole mark breathes,
     scale 1 ↔ 1.08 and opacity 0.82 ↔ 1, a 1.6 s ease-in-out cycle (800 ms each way).
     Brand colour (@color/pulsar_splash_mark, light/dark) on the connect screen's
     background. Sized for
     the central 2/3 safe zone of the 108dp splash icon canvas. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:name="mark_root" android:width="108dp" android:height="108dp"
        android:viewportWidth="108" android:viewportHeight="108" android:alpha="0.82">
      <group android:name="mark" android:pivotX="54" android:pivotY="54">
        <path android:strokeColor="@color/pulsar_splash_mark" android:strokeWidth="2.4" android:strokeAlpha="0.20"
            android:fillColor="#00000000"
            android:pathData="M54,54 m-30,0 a30,30 0 1,1 60,0 a30,30 0 1,1 -60,0"/>
        <path android:strokeColor="@color/pulsar_splash_mark" android:strokeWidth="2.8" android:strokeAlpha="0.45"
            android:fillColor="#00000000"
            android:pathData="M54,54 m-20,0 a20,20 0 1,1 40,0 a20,20 0 1,1 -40,0"/>
        <path android:strokeColor="@color/pulsar_splash_mark" android:strokeWidth="3.2"
            android:fillColor="#00000000"
            android:pathData="M54,54 m-10.6,0 a10.6,10.6 0 1,1 21.2,0 a10.6,10.6 0 1,1 -21.2,0"/>
        <path android:fillColor="@color/pulsar_splash_mark"
            android:pathData="M54,54 m-4.6,0 a4.6,4.6 0 1,1 9.2,0 a4.6,4.6 0 1,1 -9.2,0"/>
      </group>
    </vector>
  </aapt:attr>
  <target android:name="mark">
    <aapt:attr name="android:animation">
      <set>
        <objectAnimator android:propertyName="scaleX" android:valueFrom="1" android:valueTo="1.08"
            android:duration="800" android:repeatCount="infinite" android:repeatMode="reverse"
            android:interpolator="@android:interpolator/accelerate_decelerate"/>
        <objectAnimator android:propertyName="scaleY" android:valueFrom="1" android:valueTo="1.08"
            android:duration="800" android:repeatCount="infinite" android:repeatMode="reverse"
            android:interpolator="@android:interpolator/accelerate_decelerate"/>
      </set>
    </aapt:attr>
  </target>
  <target android:name="mark_root">
    <aapt:attr name="android:animation">
      <objectAnimator android:propertyName="alpha" android:valueFrom="0.82" android:valueTo="1"
          android:duration="800" android:repeatCount="infinite" android:repeatMode="reverse"
          android:interpolator="@android:interpolator/accelerate_decelerate"/>
    </aapt:attr>
  </target>
</animated-vector>
"""
with open(os.path.join(drawable_dir, "splash_icon.xml"), "w") as f:
    f.write(splash_icon)
print("  + res/drawable/splash_icon.xml (animated, desktop splash-pulse)")

# ── 2) values-v31 + values-night-v31/themes.xml — splash attrs (API 31+; below 31
#      there is no system splash, so no compat needed). BOTH are needed: Android ranks the
#      night qualifier ABOVE the API level, so on a dark-mode phone the generated
#      values-night/themes.xml (no splash attrs) beat values-v31 and the system showed the
#      plain launcher icon. The parent is read from the generated base theme so the
#      override never drifts from what `tauri android init` emits. ──
import re
base_themes = open(os.path.join(APP, "res/values/themes.xml")).read()
m = re.search(r'name="Theme\.pulsar_mobile" parent="([^"]+)"', base_themes)
PARENT = m.group(1) if m else "Theme.Material3.DayNight.NoActionBar"
def themes_v31():
    # Flat page colour only — the gradient is painted by the MainActivity overlay, which
    # takes over on the first frame.
    return f"""<resources xmlns:tools="http://schemas.android.com/tools">
    <!-- API 31+ override of the base theme: branded, animated system splash. Generated by
         scripts/patch-android-splash.py (this file REPLACES values/ resp. values-night/ on 31+). -->
    <style name="Theme.pulsar_mobile" parent="{PARENT}">
        <item name="android:windowSplashScreenBackground">@color/pulsar_splash_bg</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_icon</item>
        <!-- Informational for the system (max 1000); the icon loops for as long as the
             splash is up. -->
        <item name="android:windowSplashScreenAnimationDuration">1000</item>
    </style>
</resources>
"""
for qual in ("values-v31", "values-night-v31"):
    d = os.path.join(APP, "res", qual)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "themes.xml"), "w") as f:
        f.write(themes_v31())
    print(f"  + res/{qual}/themes.xml (parent {PARENT})")

# ── 3) MainActivity: splash overlay SPLASH_HOLD_MS + edge-to-edge ──
# The system splash dismisses on the first drawn frame and only takes a flat colour, so
# that first frame is a native overlay on the decor view: the connect screen's radial
# glows (body background in ui/css/components.css) + the same animated mark at the same
# size as the system splash icon (288dp, no icon background), so the hand-off is
# seamless. It also covers the still-empty webview, then fades out.
ma_path = os.path.join(APP, "java/dev/pulsar/app/MainActivity.kt")
# Always rewritten (not "if not patched"), so a changed SPLASH_HOLD_MS reaches an
# already-patched project too.
ma = """package dev.pulsar.app

import android.graphics.drawable.Animatable
import android.graphics.drawable.ColorDrawable
import android.graphics.drawable.Drawable
import android.graphics.drawable.GradientDrawable
import android.graphics.drawable.LayerDrawable
import android.os.Bundle
import android.view.Gravity
import android.view.ViewGroup
import android.widget.FrameLayout
import android.widget.ImageView
import androidx.activity.enableEdgeToEdge

class MainActivity : TauriActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    enableEdgeToEdge()
    super.onCreate(savedInstanceState)
    showSplash()
  }

  private fun showSplash() {
    val overlay = FrameLayout(this)
    overlay.background = splashBackground()
    overlay.isClickable = true // swallow touches until the UI is revealed
    val mark = getDrawable(R.drawable.splash_icon)
    val icon = ImageView(this)
    icon.setImageDrawable(mark)
    val size = (288 * resources.displayMetrics.density).toInt()
    overlay.addView(icon, FrameLayout.LayoutParams(size, size, Gravity.CENTER))
    (window.decorView as ViewGroup).addView(
      overlay, ViewGroup.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT))
    (mark as? Animatable)?.start()
    overlay.postDelayed({
      overlay.animate().alpha(0f).setDuration(300).withEndAction {
        (mark as? Animatable)?.stop()
        (overlay.parent as? ViewGroup)?.removeView(overlay)
      }.start()
    }, __HOLD_MS__L)
  }

  // body { background: radial-gradient(120% 70% at 50% -8%, --brand-soft, transparent 55%),
  //   radial-gradient(80% 50% at 108% 4%, --cyan-soft, transparent 50%), --bg } — the
  // ellipses approximated by circles sized from the screen width.
  private fun splashBackground(): Drawable {
    val w = resources.displayMetrics.widthPixels.toFloat()
    fun glow(color: Int, cx: Float, cy: Float, radius: Float) =
      GradientDrawable(GradientDrawable.Orientation.TOP_BOTTOM, intArrayOf(color, color and 0x00FFFFFF)).apply {
        gradientType = GradientDrawable.RADIAL_GRADIENT
        gradientRadius = radius
        setGradientCenter(cx, cy)
      }
    return LayerDrawable(arrayOf(
      ColorDrawable(getColor(R.color.pulsar_splash_bg)),
      glow(getColor(R.color.pulsar_splash_glow), 0.5f, -0.08f, w * 0.85f),
      glow(getColor(R.color.pulsar_splash_glow2), 1.08f, 0.04f, w * 0.5f),
    ))
  }
}
""".replace("__HOLD_MS__", str(SPLASH_HOLD_MS))
open(ma_path, "w").write(ma)
print(f"  + MainActivity: splash overlay {SPLASH_HOLD_MS} ms + edge-to-edge")
print("splash patch done")
